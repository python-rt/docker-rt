#!/bin/bash
# Configures RT from environment variables and, on the first start, initializes it (see README.md).

set -euo pipefail

: "${RT_WEB_DOMAIN:=localhost}"
: "${RT_WEB_PORT:=8080}"
: "${RT_CANONICALIZE_REDIRECT_URLS:=0}"
: "${RT_MAIL_COMMAND:=testfile}"
: "${RT_LOG_LEVEL:=info}"
: "${RT_ROOT_PASSWORD:=}"
: "${RT_SECRET_KEY:=}"
: "${RT_INIT_DIR:=/docker-entrypoint-init.d}"

init_marker=/opt/rt/var/.docker-initialized

log() {
  echo "docker-entrypoint: $*" >&2
}

# quotes a value as Perl string literal
perl_quote() {
  local value=${1//\\/\\\\}
  printf "'%s'" "${value//\'/\\\'}"
}

if [[ ! "$RT_WEB_PORT" =~ ^[0-9]+$ ]]; then
  log "RT_WEB_PORT must be a number: $RT_WEB_PORT"
  exit 1
fi

if [[ ! "$RT_CANONICALIZE_REDIRECT_URLS" =~ ^[01]$ ]]; then
  log "RT_CANONICALIZE_REDIRECT_URLS must be 0 or 1: $RT_CANONICALIZE_REDIRECT_URLS"
  exit 1
fi

# RT warns without a secret key (used e.g. for password reset tokens); a random one is created once and kept
if [[ -z "$RT_SECRET_KEY" ]]; then
  secret_key_file=/opt/rt/var/secret-key
  if [[ ! -s "$secret_key_file" ]]; then
    (umask 077 && head -c 48 /dev/urandom | base64 -w 0 > "$secret_key_file")
  fi
  RT_SECRET_KEY=$(< "$secret_key_file")
fi

# written on every start, so changed variables are applied after a restart; RT loads all files in RT_SiteConfig.d,
# own configuration can be mounted there as well (e.g. RT_SiteConfig.d/50-custom.pm)
mkdir -p /opt/rt/etc/RT_SiteConfig.d
(umask 077 && cat > /opt/rt/etc/RT_SiteConfig.d/00-docker.pm) <<EOF
# generated by docker-entrypoint.sh from environment variables, changes are overwritten on start
Set(\$WebDomain, $(perl_quote "$RT_WEB_DOMAIN"));
Set(\$WebPort, $RT_WEB_PORT);
Set(\$CanonicalizeRedirectURLs, $RT_CANONICALIZE_REDIRECT_URLS);
Set(\$MailCommand, $(perl_quote "$RT_MAIL_COMMAND"));
Set(\$LogToSTDERR, $(perl_quote "$RT_LOG_LEVEL"));
Set(\$SecretKey, $(perl_quote "$RT_SECRET_KEY"));

1;
EOF

initialize() {
  if [[ -n "$RT_ROOT_PASSWORD" ]]; then
    log "setting the password of root"
    rt-user root --password "$RT_ROOT_PASSWORD" > /dev/null
  fi

  if [[ -d "$RT_INIT_DIR" ]]; then
    local file
    for file in "$RT_INIT_DIR"/*; do
      case "$file" in
        *.pl)
          log "inserting initial data $file"
          rt-initdata "$file" > /dev/null
          ;;
        *.sh)
          log "running $file"
          bash "$file"
          ;;
        *)
          [[ -e "$file" ]] && log "ignoring $file (neither .pl nor .sh)"
          ;;
      esac
    done
  fi

  touch "$init_marker"
}

# initialize only when starting RT, not e.g. for "docker run ... bash"
if [[ "${1:-}" == */rt-server || "${1:-}" == rt-server ]] && [[ ! -e "$init_marker" ]]; then
  initialize
fi

exec "$@"
